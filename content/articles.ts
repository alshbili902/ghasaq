export function getArticleBySlug(slug: string): ArticleItem | undefined {
  return articles.find((article) => article.slug === slug);
}

export function getArticlesByCategory(
  categoryId: ArticleCategoryId | "all"
): readonly ArticleItem[] {
  if (categoryId === "all") return articles;
  return articles.filter((article) => article.categoryId === categoryId);
}

export function getRelatedArticles(
  currentArticle: ArticleItem,
  limit = 3
): readonly ArticleItem[] {
  const sameCategory = articles.filter(
    (a) => a.slug !== currentArticle.slug && a.categoryId === currentArticle.categoryId
  );
  const others = articles.filter(
    (a) => a.slug !== currentArticle.slug && a.categoryId !== currentArticle.categoryId
  );
  return [...sameCategory, ...others].slice(0, limit);
}
