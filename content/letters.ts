export function getLetterBySlug(slug: string): LetterItem | undefined {
  return letters.find((letter) => letter.slug === slug);
}

export function getLettersByCategory(categoryId: LetterCategoryId | "all"): readonly LetterItem[] {
  if (categoryId === "all") return letters;
  return letters.filter((letter) => letter.categoryId === categoryId);
}

export function getAdjacentLetters(currentSlug: string): {
  previous: LetterItem | null;
  next: LetterItem | null;
} {
  const index = letters.findIndex((letter) => letter.slug === currentSlug);
  if (index === -1) {
    return { previous: null, next: null };
  }
  return {
    previous: index > 0 ? letters[index - 1] : null,
    next: index < letters.length - 1 ? letters[index + 1] : null,
  };
}
